// Live mutable in-memory array for local development
export let liveLocalDevApplications = [...INITIAL_MOCK_APPLICATIONS];

export function resetLocalDevApplications() {
  liveLocalDevApplications = [...INITIAL_MOCK_APPLICATIONS];
  return liveLocalDevApplications;
}

export function addLocalDevApplication(app) {
  const newApp = {
    ...app,
    id: Date.now(),
    has_resume: Boolean(app.resume_name || app.resume_data),
    created_at: app.created_at || new Date().toISOString(),
  };
  liveLocalDevApplications.unshift(newApp);
  return newApp;
}

export function deleteLocalDevApplication(id) {
  const numId = Number(id);
  liveLocalDevApplications = liveLocalDevApplications.filter((a) => a.id !== numId && String(a.id) !== String(id));
  return liveLocalDevApplications;
}
