export let liveLocalDevSubscribers = [...INITIAL_MOCK_SUBSCRIBERS];

export function resetLocalDevSubscribers() {
  liveLocalDevSubscribers = [...INITIAL_MOCK_SUBSCRIBERS];
  return liveLocalDevSubscribers;
}

export function addLocalDevSubscriber(email) {
  const trimmed = (email || '').trim().toLowerCase();
  if (!trimmed) return null;
  const existing = liveLocalDevSubscribers.find((s) => s.email.toLowerCase() === trimmed);
  if (existing) return existing;
  const newSub = {
    id: Date.now(),
    email: trimmed,
    created_at: new Date().toISOString(),
  };
  liveLocalDevSubscribers.unshift(newSub);
  return newSub;
}

export function deleteLocalDevSubscriber(id) {
  const numId = Number(id);
  liveLocalDevSubscribers = liveLocalDevSubscribers.filter((s) => s.id !== numId && String(s.id) !== String(id));
  return liveLocalDevSubscribers;
}
